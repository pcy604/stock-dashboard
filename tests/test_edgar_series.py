"""edgar_client._series — 분기 도출 규칙 (2026-10-17, TSLA 공시 대조 후 고정)"""
import edgar_client as E


def _node(facts):
    return {'units': {'USD': [dict(start=s, end=e, val=v, form=f) for s, e, v, f in facts]}}


# TSLA 2025 실제 공시값($M) — 3개월치(10-Q)와 누적(YTD)이 함께 실린다
REV = _node([('2025-01-01', '2025-03-31', 19335, '10-Q'), ('2025-04-01', '2025-06-30', 22496, '10-Q'),
             ('2025-01-01', '2025-06-30', 41831, '10-Q'), ('2025-07-01', '2025-09-30', 28095, '10-Q'),
             ('2025-01-01', '2025-09-30', 69926, '10-Q'), ('2025-01-01', '2025-12-31', 94827, '10-K')])
# EPS: 6개월 누적 0.45 − 1분기 0.12 = 0.33 이 우연히 맞아도, 규칙은 '공시된 3개월 값'이 이긴다
EPS = _node([('2025-01-01', '2025-03-31', 0.12, '10-Q'), ('2025-04-01', '2025-06-30', 0.33, '10-Q'),
             ('2025-01-01', '2025-06-30', 0.40, '10-Q'), ('2025-07-01', '2025-09-30', 0.39, '10-Q'),
             ('2025-01-01', '2025-09-30', 0.84, '10-Q'), ('2025-01-01', '2025-12-31', 1.08, '10-K')])


def test_revenue_quarters_and_q4_derived():
    q = E._series(REV, 'quarter')
    assert q['2025-03'] == 19335 and q['2025-06'] == 22496 and q['2025-09'] == 28095
    assert q['2025-12'] == 94827 - 69926 == 24901          # 공식 4Q 매출 24,901


def test_eps_direct_only_no_subtraction():
    q = E._series(EPS, 'quarter', additive=False)
    assert q['2025-06'] == 0.33                             # 0.40−0.12=0.28 이 아니라 공시값
    assert '2025-12' not in q                               # FY−9M 은 4Q EPS 가 아니다 → 비움


def test_annual():
    assert E._series(REV, 'annual') == {'2025': 94827}
